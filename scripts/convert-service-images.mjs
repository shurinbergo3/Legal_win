#!/usr/bin/env node
import sharp from 'sharp';
import { readdir, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';

const SRC_DIR = path.resolve('Image/для лендингов');
const OUT_DIR = path.resolve('public/services');

const SLUG_ORDER = [
  'karta-pobytu',
  'karta-stalego-pobytu',
  'obywatelstwo',
  'ochrona-miedzynarodowa',
  'apelacje',
  'kod-95',
  'pesel',
  'meldunek',
  'akty-stanu-cywilnego',
  'apostille',
  'wymiana-prawa-jazdy',
  'zaswiadczenia-zus-us',
  'zaswiadczenie-o-niekaralnosci',
  'tlumaczenia-przysiegle',
  'zaproszenia',
  'odbior-z-lotniska',
  'wyszukiwanie-mieszkania',
  'tlumacz-na-wizyty',
  'pomoc-w-zatrudnieniu',
  'zapis-dzieci-do-szkoly',
  'blog'
];

if (!existsSync(OUT_DIR)) await mkdir(OUT_DIR, { recursive: true });

const all = (await readdir(SRC_DIR))
  .filter((f) => /\.(jpe?g|png)$/i.test(f))
  .sort();

if (all.length !== SLUG_ORDER.length) {
  console.warn(`! sources=${all.length} slots=${SLUG_ORDER.length}`);
}

const pairs = SLUG_ORDER.map((slug, i) => [all[i], slug]).filter(([s]) => s);

for (const [filename, slug] of pairs) {
  const inPath = path.join(SRC_DIR, filename);
  const outPath = path.join(OUT_DIR, `${slug}.webp`);
  const meta = await sharp(inPath).metadata();
  const targetWidth = Math.min(1600, meta.width ?? 1600);
  await sharp(inPath)
    .rotate()
    .resize({ width: targetWidth, withoutEnlargement: true })
    .webp({ quality: 72, effort: 6 })
    .toFile(outPath);
  console.log(`✔ ${slug}.webp  ←  ${filename}`);
}

// Generate larger / sharper blur placeholders so the "pop-in" fades smoothly
// under the hero's dark gradient overlay.
const blurs = {};
for (const [, slug] of pairs) {
  const outPath = path.join(OUT_DIR, `${slug}.webp`);
  const buf = await sharp(outPath)
    .resize({ width: 32 })
    .webp({ quality: 55 })
    .toBuffer();
  blurs[slug] = `data:image/webp;base64,${buf.toString('base64')}`;
}
// Write a TS-ready blur lookup file keyed by /services/<slug>.webp.
import { writeFile } from 'node:fs/promises';
const tsLines = [
  '// Auto-generated by scripts/convert-service-images.mjs.',
  '// Per-image blur placeholders (32px wide, webp q55).',
  'export const SERVICE_BLUR: Record<string, string> = {',
  ...Object.entries(blurs).map(
    ([slug, dataUrl]) => `  '/services/${slug}.webp':\n    '${dataUrl}',`
  ),
  '};',
  ''
].join('\n');
await writeFile(path.resolve('src/lib/__service-blur.generated.ts'), tsLines);
console.log('\n✔ wrote src/lib/__service-blur.generated.ts');
